/**
 * @category evergreen
 * @purpose Verify product token staleness is decided by content, not file times (Spec 114 R4; Spec 129 U8, Req 5.8)
 */

import * as fs from 'fs';
import * as path from 'path';
import * as os from 'os';
import { isProductTokenStale, getProductTokenOutputPaths } from '../staleness';
import { generateProductTokens } from '../generateProductTokens';
import { sameOutput, withoutTimestamps, compareOutput } from '../freshness';
import type { ResolvedConfig } from '../../config/ConfigLoader';

jest.mock('../generateProductTokens', () => ({ generateProductTokens: jest.fn() }));
const render = generateProductTokens as jest.MockedFunction<typeof generateProductTokens>;

const FILES = ['ProductTokens.web.css', 'ProductTokens.ios.swift', 'ProductTokens.android.kt'];

describe('isProductTokenStale — by content', () => {
  let tmpDir: string;
  let sourceDir: string;
  let outputDir: string;

  function makeConfig(): ResolvedConfig {
    return {
      name: 'Test', abbreviation: 'T', themes: [], tokenSourceRoot: tmpDir, tokenSourceMode: 'package',
      componentTokenDirs: [], outputDir: tmpDir, configDir: tmpDir, productTokens: sourceDir,
    } as ResolvedConfig;
  }

  /** What a fresh render writes: a body per file, with the header a package version names. */
  function renders(body: string, version = '1.0.0'): void {
    render.mockImplementation((_config, options) => {
      for (const f of FILES) fs.writeFileSync(path.join(options!.renderTo!, f), `/* Generated by @3fn/core ${version} */\n${body} ${f}\n`);
    });
  }

  function writeOutput(body: string, version = '1.0.0'): void {
    fs.mkdirSync(outputDir, { recursive: true });
    for (const f of FILES) fs.writeFileSync(path.join(outputDir, f), `/* Generated by @3fn/core ${version} */\n${body} ${f}\n`);
  }

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'staleness-'));
    sourceDir = path.join(tmpDir, 'product-tokens');
    outputDir = path.join(tmpDir, 'product');
    fs.mkdirSync(sourceDir, { recursive: true });
    fs.writeFileSync(path.join(sourceDir, 'colors.yaml'), 'tokens: {}');
    render.mockReset();
  });
  afterEach(() => fs.rmSync(tmpDir, { recursive: true, force: true }));

  test('returns true when --force is set, without rendering', () => {
    writeOutput('a');
    expect(isProductTokenStale(makeConfig(), true)).toBe(true);
    expect(render).not.toHaveBeenCalled();
  });

  test('returns true when an output file is missing', () => {
    renders('a');
    expect(isProductTokenStale(makeConfig())).toBe(true);
  });

  test('returns false when a fresh render equals the output, whatever the file times say', () => {
    renders('a');
    writeOutput('a');
    // The output is OLDER than the source: file times would have said stale.
    const now = Date.now();
    for (const p of getProductTokenOutputPaths(makeConfig())) fs.utimesSync(p, new Date(now - 60_000), new Date(now - 60_000));
    fs.utimesSync(path.join(sourceDir, 'colors.yaml'), new Date(now), new Date(now));
    expect(isProductTokenStale(makeConfig())).toBe(false);
  });

  test('returns true when the output differs from a fresh render, though it is newer than every source', () => {
    renders('b');
    writeOutput('a');
    const now = Date.now();
    fs.utimesSync(path.join(sourceDir, 'colors.yaml'), new Date(now - 60_000), new Date(now - 60_000));
    // The output is NEWER than the source: file times would have said fresh.
    expect(isProductTokenStale(makeConfig())).toBe(true);
  });

  test('an upgrade shows: the header names the package version', () => {
    renders('a', '2.0.0');
    writeOutput('a', '1.0.0');
    expect(isProductTokenStale(makeConfig())).toBe(true);
  });

  test('one differing file is enough', () => {
    renders('a');
    writeOutput('a');
    fs.writeFileSync(path.join(outputDir, 'ProductTokens.android.kt'), 'edited\n');
    expect(isProductTokenStale(makeConfig())).toBe(true);
  });

  test('a render that throws reads as stale (the real run then says why)', () => {
    writeOutput('a');
    render.mockImplementation(() => { throw new Error('refused'); });
    expect(isProductTokenStale(makeConfig())).toBe(true);
  });

  test('a render that wrote nothing (no categories) reads as stale', () => {
    writeOutput('a');
    render.mockImplementation(() => undefined);
    expect(isProductTokenStale(makeConfig())).toBe(true);
  });

  test('returns true when productTokens path does not exist', () => {
    const config = makeConfig();
    config.productTokens = '/nonexistent/path';
    expect(isProductTokenStale(config)).toBe(true);
  });

  test('renders into a temporary directory and removes it', () => {
    renders('a');
    writeOutput('a');
    isProductTokenStale(makeConfig());
    const dir = render.mock.calls[0][1]!.renderTo!;
    expect(dir).not.toBe(outputDir);
    expect(fs.existsSync(dir)).toBe(false);
  });

  test('does not read file times at all: the module has no mtime or stat call', () => {
    const source = fs.readFileSync(path.join(__dirname, '..', 'staleness.ts'), 'utf-8')
      .replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '');
    expect(source).not.toMatch(/mtime|statSync|utimes/);
  });
});

describe('the comparison itself', () => {
  test('a header timestamp is not a difference; any other text is', () => {
    expect(sameOutput('// built 2026-11-08T01:02:03.456Z\nx', '// built 2025-01-01T00:00:00Z\nx')).toBe(true);
    expect(sameOutput('// built 2026-11-08T01:02:03Z\nx', '// built 2026-11-08T01:02:03Z\ny')).toBe(false);
    expect(withoutTimestamps('a 2026-11-08T01:02:03Z b')).toBe('a <timestamp> b');
  });

  test('compareOutput lists differing and missing files, and compares the fresh directory\'s files only', () => {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cmp-'));
    try {
      const fresh = path.join(root, 'fresh'); const actual = path.join(root, 'actual');
      fs.mkdirSync(path.join(fresh, 'sub'), { recursive: true }); fs.mkdirSync(path.join(actual, 'sub'), { recursive: true });
      fs.writeFileSync(path.join(fresh, 'same.txt'), 's'); fs.writeFileSync(path.join(actual, 'same.txt'), 's');
      fs.writeFileSync(path.join(fresh, 'sub', 'diff.txt'), 'new'); fs.writeFileSync(path.join(actual, 'sub', 'diff.txt'), 'old');
      fs.writeFileSync(path.join(fresh, 'absent.txt'), 'x');
      fs.writeFileSync(path.join(actual, 'extra.txt'), 'only on disk');
      expect(compareOutput(fresh, actual)).toEqual({ compared: 3, differing: ['sub/diff.txt'], missing: ['absent.txt'] });
    } finally {
      fs.rmSync(root, { recursive: true, force: true });
    }
  });
});

describe('getProductTokenOutputPaths', () => {
  test('returns paths for all three platform files', () => {
    const config = { outputDir: '/tmp/dist' } as any;
    const paths = getProductTokenOutputPaths(config);
    expect(paths).toHaveLength(3);
    expect(paths[0]).toContain('ProductTokens.web.css');
    expect(paths[1]).toContain('ProductTokens.ios.swift');
    expect(paths[2]).toContain('ProductTokens.android.kt');
  });
});

export interface SyncOptions {
  projectRoot: string;
  /** Report only; never write (any TTY state). */
  dryRun?: boolean;
  /** Apply updates without the terminal confirmation (the off-TTY path). */
  apply?: boolean;
  /** `deleted-by-you` paths (or `<file>#<key>` ids) to re-add. */
  restore?: string[];
  /** `conflict` paths (or `<file>#<key>` ids) to overwrite. */
  overwrite?: string[];
  /** The retired `--force` / `--accept-all` flags were passed (reported, not honored). */
  retiredForce?: boolean;
  /** Test seam — defaults to `process.stdin.isTTY`. */
  isTTY?: boolean;
  /** Test seam — the terminal batch confirmation. */
  confirm?: (question: string) => Promise<boolean>;
  /** Test seam — the `.gitignore` block offer's own `[y/N]` question (default No; PR-9). */
  confirmGitignoreBlock?: (question: string) => Promise<boolean>;
  /** `--migrate-components`: relocate forks to src/components/<Name>/, remove unmodified copies. */
  migrateComponents?: boolean;
  /** Test seam — the migration's package fetcher (default: the consumer's own npm rail). */
  fetcher?: PackageFetcher;
  /** `--repair-npmrc`: remove the `@3fn` → GitHub Packages mapping line (Req 5.1). */
  repairNpmrc?: boolean;
  /** `--repair-tsconfig`: remove tsconfig.test.json's raw-src re-pins (Req 5.2). */
  repairTsconfig?: boolean;
  /** Test seam — the config-module loader for the name contract's output directory (Task 6). */
  configLoader?: ConfigModuleLoader;
  /**
   * `--migrate-legacy` (C7 Migration item 4; Task 16.5): remove the release-1 legacy copies, then — in the
   * same run — attach the agent layer. Offered and honored ONLY when attach is available.
   */
  migrateLegacy?: boolean;
  /** `--target=<t>` (repeatable): the target(s) `--migrate-legacy`'s attach step adds beside the manifest's `attachedTargets`. */
  targets?: string[];
  /**
   * Test seam — the package side of the generated surfaces (default: the installed package's
   * `dist/generator/consumer-entry.js`, `emitConsumer` in `mode: 'sync'`). `null` = unavailable.
   */
  agentLayer?: AgentLayerSource | null;
}

/** One file the package's agent-layer lane emits (C20's `emitConsumer` file list). */
export interface EmittedAgentFile {
  path: string;
  content: string;
  grain: 'file' | 'region';
}

/** The package side of the generated surfaces (C7: "freshly generated, by `emitConsumer`"). */
export interface AgentLayerSource {
  /** The packaged profile's declared targets (C12's single list — never a literal here). */
  declaredTargets(): readonly string[];
  emit(target: string): Promise<{ files: EmittedAgentFile[]; warnings: string[] }>;
}

/** The default source: the installed package's own compiled lane. Throws (the reason) when it cannot load. */
function bundleAgentLayerSource(pkgRoot: string, projectRoot: string): AgentLayerSource {
  const { entry, profile } = resolveAgentTarget(pkgRoot, undefined, 'sync');
  return {
    declaredTargets: () => profile.targets,
    emit: async (target) => {
      const r = await entry.emitConsumer({ packageRoot: pkgRoot, consumerRoot: projectRoot, target, mode: 'sync' });
      return { files: r.files, warnings: r.warnings };
    },
  };
}


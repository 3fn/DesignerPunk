/**
 * Whether the attach step can run here — decided through `attach`'s own rules: the agent-layer lane loads
 * from the installed package, `attach` would not refuse this repo (born or package-mode only), every
 * requested target is declared, and the emission succeeds for each target it would attach.
 */
async function attachAvailability(
  projectRoot: string,
  manifest: DesignerPunkManifest,
  requested: readonly string[],
  agentLayer: AgentLayerSource | null,
  agentLayerReason: string,
  emitFor: (target: string) => Promise<unknown>,
): Promise<AttachAvailability> {
  if (!agentLayer) return { available: false, reason: agentLayerReason || 'the agent-layer lane is unavailable' };
  const refusal = attachRefusal(projectRoot);
  if (refusal.message !== null) return { available: false, reason: `attach refuses this repo: ${refusal.message}` };
  const declared = agentLayer.declaredTargets();
  const undeclared = requested.filter((t) => !declared.includes(t));
  if (undeclared.length > 0) {
    return { available: false, reason: `target ${undeclared.join(', ')} is not declared by the installed package (declared: ${declared.join(', ')})` };
  }
  const targets = [...new Set<string>([...manifest.attachedTargets, ...requested])];
  try {
    for (const t of targets) await emitFor(t);
  } catch (err) {
    return { available: false, reason: (err as Error).message };
  }
  return { available: true, targets, declared };
}

/**
 * `--migrate-legacy`: the removal, then — in the same run, through `attach`'s code path
 * (`emitAgentLayer`) — the attach step for each target. Refuses, removing nothing, when attach is not
 * available or there is no target. Returns true iff it ran.
 */
async function runMigrateLegacy(
  projectRoot: string,
  pkgRoot: string,
  manifest: DesignerPunkManifest,
  outcome: SyncOutcome,
): Promise<boolean> {
  if (!outcome.legacyCopies) {
    console.log('\n  --migrate-legacy: this manifest records no legacy copies — nothing to migrate.');
    return false;
  }
  const avail = outcome.attach;
  if (!avail || !avail.available) {
    outcome.trace.push('migrate-legacy:refused');
    console.log(`\n  ${migrateLegacyRefusedMessage(avail && !avail.available ? avail.reason : 'attach availability was not established')}`);
    return false;
  }
  if (avail.targets.length === 0) {
    outcome.trace.push('migrate-legacy:refused');
    console.log(`\n  ${migrateLegacyNeedsTargetMessage(avail.declared)}`);
    return false;
  }
  outcome.legacyRemoval = removeLegacyCopies(projectRoot, manifest.entries);
  outcome.trace.push(`migrate-legacy:removed:${outcome.legacyRemoval.removed.length}`);
  console.log(`\n${legacyRemovalSummary(outcome.legacyRemoval)}`);
  for (const target of avail.targets) {
    const layer = await emitAgentLayer({ pkgRoot, repoRoot: projectRoot, requestedTarget: target, mode: 'attach', manifest });
    outcome.trace.push(`attach:${target}`);
    outcome.applied.push(...layer.files);
    const parts = [`${layer.written} file${layer.written === 1 ? '' : 's'} written`];
    if (layer.unchanged > 0) parts.push(`${layer.unchanged} unchanged`);
    if (layer.collided > 0) parts.push(`${layer.collided} skipped (see warnings above)`);
    console.log(`  ✓ attached ${target} — ${parts.join(', ')}`);
  }
  return true;
}

export function agentLayerUnavailableMessage(reason: string): string {
  return `could not generate DesignerPunk's agent layer from the installed package — ${reason}. Your generated agent files were not checked.`;
}

export interface GeneratedSurfaces {
  /** File grain (paths) and region grain (`<file>#managed` ids), classified together. */
  files: ClassificationResult;
  /** Package content by path / region id — what an apply writes. */
  contents: Map<string, string>;
  /** `untracked-new` items, with the target whose `attach` would record them (the catalog row names it). */
  untrackedNew: Array<{ path: string; target: string }>;
  /** Recorded regions whose markers are gone — the catalog's "markers missing" string; never written. */
  markersMissing: string[];
  /** The lane's Req 13 degradation warnings. */
  warnings: string[];
}

function markersFor(file: string) {
  return regionMarkers(file.endsWith('.md') ? CLAUDE_MD_COMMENT : GITIGNORE_COMMENT);
}

/**
 * The directories the package's agent layer writes into, derived from the emission itself (never a list
 * kept here): a path's first two segments (`.claude/agents`, `.kiro/steering`, `.claude/skills`, …). A
 * recorded generated entry under one of them that the package no longer emits is `removed`; a consumer's
 * own file there is never classified (it has no entry and no package counterpart).
 */
function agentLayerRoots(paths: string[]): string[] {
  const roots = new Set<string>();
  for (const p of paths) {
    const seg = p.split('/');
    roots.add(seg.length >= 3 ? seg.slice(0, 2).join('/') : seg.length === 2 ? seg[0] : p);
  }
  return [...roots].sort();
}

/**
 * Classify the generated surfaces for `targets` (the manifest's `attachedTargets` — C7: "the package side
 * of the generated surfaces is freshly generated, by `emitConsumer`, for the manifest's attachedTargets").
 * A target with nothing recorded yet yields `untracked-new` (reported, never applied); once `attach` has
 * recorded any of its surfaces, a newly emitted file is `new`.
 */
async function classifyGenerated(
  projectRoot: string,
  targets: readonly string[],
  emitFor: (target: string) => Promise<{ files: EmittedAgentFile[]; warnings: string[] }>,
  entries: Record<string, ManifestEntry>,
  ignore: IgnoreFilter,
): Promise<GeneratedSurfaces> {
  const contents = new Map<string, string>();
  const targetOf = new Map<string, string>();
  const pkgFiles: ScannedFile[] = [];
  const regions: Array<EmittedAgentFile & { target: string }> = [];
  const warnings: string[] = [];
  for (const target of targets) {
    const emitted = await emitFor(target);
    for (const w of emitted.warnings) if (!warnings.includes(w)) warnings.push(w);
    for (const f of emitted.files) {
      const id = f.grain === 'region' ? regionEntryId(f.path) : f.path;
      if (contents.has(id)) continue;
      contents.set(id, f.content);
      targetOf.set(id, target);
      if (f.grain === 'region') regions.push({ ...f, target });
      else pkgFiles.push({ relativePath: f.path, absolutePath: '', hash: hashBuffer(f.content) });
    }
  }
  const recordedTargets = new Set<string>();
  for (const [id, target] of targetOf) if (entries[id]?.origin === 'generated') recordedTargets.add(target);

  const roots = agentLayerRoots(pkgFiles.map((f) => f.relativePath));
  const files = classifyFiles(pkgFiles, scanFiles(projectRoot, roots), entries, ignore, roots, {
    origin: 'generated',
    untracked: (rel) => !recordedTargets.has(targetOf.get(rel) ?? ''),
  });

  const markersMissing: string[] = [];
  for (const r of regions) {
    if (ignore.isIgnored(r.path)) continue;
    const id = regionEntryId(r.path);
    const abs = path.join(projectRoot, r.path);
    const text = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf-8') : undefined;
    const entry = entries[id]?.origin === 'generated' && entries[id]?.grain === 'region' ? entries[id] : undefined;
    const c = classifyRegion(text, markersFor(r.path), r.content, entry, !recordedTargets.has(r.target));
    const item = (classification: ClassifiedFile['classification'], reason?: string): ClassifiedFile => ({
      relativePath: id,
      classification,
      packageHash: hashBuffer(normalizeRegionContent(r.content)),
      ...(entry ? { manifestHash: entry.hash } : {}),
      ...(reason ? { reason } : {}),
    });
    switch (c.kind) {
      case 'unchanged': files.unchanged.push(item('unchanged')); break;
      case 'updated-safe': files.updatedSafe.push(item('updated-safe', 'unchanged by you — package updated')); break;
      case 'conflict': files.conflicts.push(item('conflict', managedRegionEditedInsideMessage(r.path))); break;
      case 'new': files.new.push(item('new')); break;
      case 'untracked-new': files.untrackedNew.push(item('untracked-new')); break;
      case 'deleted-by-you': files.deletedByYou.push(item('deleted-by-you')); break;
      case 'adoptable': files.adoptable.push(item('unchanged')); break;
      case 'markers-missing': markersMissing.push(r.path); break;
    }
  }
  return {
    files,
    contents,
    untrackedNew: files.untrackedNew.map((f) => ({ path: f.relativePath, target: targetOf.get(f.relativePath) ?? '' })),
    markersMissing,
    warnings,
  };
}

/** Write one generated file and record exactly the bytes written (`origin: 'generated'`). */
function applyGeneratedFile(projectRoot: string, rel: string, content: string, entries: Record<string, ManifestEntry>): boolean {
  try {
    const abs = path.join(projectRoot, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, 'utf-8');
    entries[rel] = { hash: hashBuffer(content), grain: 'file', origin: 'generated' };
    return true;
  } catch (err) {
    console.error(`  ❌ Failed to apply ${rel}: ${(err as Error).message}`);
    return false;
  }
}

/**
 * Write one managed region (`<file>#managed`): splice it when the markers are there, create the file when it
 * is absent, append the region when the file has none (a `new` region — never a recorded one whose markers
 * she removed, which the classifier reports and never routes here). Outside bytes are never changed.
 */
function applyGeneratedRegion(projectRoot: string, id: string, content: string, entries: Record<string, ManifestEntry>): boolean {
  const file = id.slice(0, -'#managed'.length);
  const abs = path.join(projectRoot, file);
  const markers = markersFor(file);
  try {
    let text: string;
    if (!fs.existsSync(abs)) {
      text = wrapRegion(markers, content);
    } else {
      const existing = fs.readFileSync(abs, 'utf-8');
      const spliced = spliceRegion(existing, markers, content, file);
      text = spliced.ok ? spliced.text : appendRegion(existing, markers, content);
    }
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, text, 'utf-8');
    entries[id] = { hash: hashBuffer(normalizeRegionContent(content)), grain: 'region', origin: 'generated' };
    return true;
  } catch (err) {
    console.error(`  ❌ Failed to apply ${id}: ${(err as Error).message}`);
    return false;
  }
}

/**
 * The targets whose MCP keys `sync` reconciles: `attachedTargets`, plus any target the manifest records
 * keys for without attaching its agent layer (`init --skip-agents`; `attach --reference`, whose manifest
 * exists so `sync` can repair approval drift — DD22).
 */
function keyGrainTargets(manifest: DesignerPunkManifest): HarnessTarget[] {
  const targets = new Set<HarnessTarget>(manifest.attachedTargets);
  for (const surface of KEY_SURFACES) {
    if (Object.entries(manifest.entries).some(([id, e]) => e.grain === 'key' && id.startsWith(`${surface.file}#`))) targets.add(surface.target);
  }
  return [...targets];
}

/** A consume-posture manifest's package side: the reference servers only (C20 `--reference`; DD22). */
function restrictToReference(keys: Map<string, Map<string, unknown>>): void {
  for (const surfaceKeys of keys.values()) {
    for (const key of [...surfaceKeys.keys()]) {
      if (!REFERENCE_SERVERS.some((s) => key === s || key.startsWith(`mcp__${s}__`))) surfaceKeys.delete(key);
    }
  }
}


/**
 * `sync`'s report — and `sync`'s slice of the loud-failure catalog.
 *
 * Spec 123 Task 5.4 (design.md § "C7"; § "Error Handling — the loud-failure
 * catalog"). The report is ALWAYS printed before anything applies ("no class
 * applies without the report printing first"). Catalog rows are exact strings;
 * `sync.catalog.test.ts` pins each to its design row, string-equal.
 *
 * @see Spec 111 — Requirement 9; Spec 123 design.md § "C7"
 */

import type { ClassificationResult } from './Classifier';
import type { SurfaceKeyResult } from './KeyGrain';

// ---------------------------------------------------------------------------
// Catalog rows (design.md § "Error Handling") — exact strings
// ---------------------------------------------------------------------------

/** Row `deleted-by-you`. */
export function deletedByYouMessage(p: string): string {
  return `${p} was generated earlier and you deleted it — not re-adding. To restore: npx designerpunk sync --restore ${p}`;
}

/** Row `untracked-new`. */
export function untrackedNewMessage(p: string, target: string): string {
  return `${p} would be generated but was never recorded — not adding it on first sync. To add it: npx designerpunk attach --target=${target}`;
}

/** Row "consumer key under our prefix" (Leonardo A-R1) — info, once per key. */
export function yoursUnderPrefixMessage(key: string): string {
  return `${key} is under DesignerPunk's prefix but was not generated by DesignerPunk — it is yours; sync will not manage or remove it`;
}

